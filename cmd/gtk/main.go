func runBatch(args []string) int {
	fs := flag.NewFlagSet("batch", flag.ContinueOnError)
	format := fs.String("format", "pgm", "输出格式")
	inDir := fs.String("in-dir", "", "输入目录（*.pgm）")
	outDir := fs.String("out-dir", "", "输出目录")
	report := fs.String("report", "", "报表路径")
	gain := fs.Int("gain", 0, "亮度增益百分比")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	if *inDir == "" || *outDir == "" || *report == "" {
		fmt.Fprintln(os.Stderr, "缺少 --in-dir、--out-dir 或 --report")
		return 2
	}
	res, err := api.RunBatch(api.BatchOptions{
		InDir:  *inDir,
		OutDir: *outDir,
		Format: *format,
		Gain:   *gain,
		Report: *report,
	})
	if err != nil {
		fmt.Fprintln(os.Stderr, "批量失败:", err)
		if errors.Is(err, api.ErrBadDir) {
			return 3
		}
		if errors.Is(err, api.ErrReportWrite) {
			return 4
		}
		return 1
	}
	for _, f := range res.Failed {
		fmt.Fprintf(os.Stderr, "跳过 %s: %v\n", f.Name, f.Err)
	}
	fmt.Printf("batch %d 个文件 -> %s，报表 %s\n", len(res.Rows), *format, *report)
	return 0
}
