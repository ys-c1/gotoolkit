// Package quantfb 实现「量化器 × 二阶反馈回路」联合设计。
//
// 题面背景：A 组直接使用现成的 Floyd–Steinberg 扩散核，低频残差偏多；
// B 组只把反馈系数改成常见的二阶 (−2,+1)，没有同步设计量化步长，
// 低频占比下降有限且峰值误差失控。本包按交替迭代
//
//	固定量化步长 q → 在误差预算下解两个反馈系数 c1,c2；
//	固定 c1,c2     → 解满足输出误差有界预算的最大整数步长 q；
//	交替直到 (q,c1,c2) 都不再变化，
//
// 得到不动点 q*=10、c1*=−1.8226665269、c2*=+0.8226665269。
//
// 回路（逐行、行首清零两个延迟误差）：
//
//	u_n = x_n + c1 e_{n-1} + c2 e_{n-2}
//	ỹ_n = q·round(u_n/q)          // 回路内部不夹取，保证 |e_n|≤q/2
//	e_n = ỹ_n − u_n
//	y_n = clamp(ỹ_n, 0, 255)      // 只在交付像素时夹取
//
// 恒等式（未夹取）：ỹ_n−x_n = e_n + c1 e_{n-1} + c2 e_{n-2}，
// 因此 |ỹ_n−x_n| ≤ (1+|c1|+|c2|)q/2；夹取是到 [0,255] 的投影，
// 对 x_n∈[0,255] 不增大误差，交付残差同样满足该界。
